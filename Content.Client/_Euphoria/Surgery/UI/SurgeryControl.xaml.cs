using Content.Shared._Euphoria.Surgery;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._Euphoria.Surgery.UI;

[GenerateTypedNameReferences]
public sealed partial class SurgeryControl : Control
{
    public Action<string>? OnButtonPressed;
    public Func<string> TooltipTextSupplier;

    private ProtoId<SurgeryActionPrototype> _surgeryId;
    private SurgerySystem _surgerySystem;

    public SurgeryControl(SurgerySystem surgerySystem, SurgeryActionPrototype surgeryActionPrototype, Func<string> tooltipTextSupplier, Control displayControl)
    {
        RobustXamlLoader.Load(this);

        _surgerySystem = surgerySystem;
        _surgeryId = surgeryActionPrototype.ID;
        TooltipTextSupplier = tooltipTextSupplier;
        SetAction(surgeryActionPrototype);
        SetDisplayControl(displayControl);

        Button.OnPressed += (_) =>
        {
            OnButtonPressed?.Invoke(_surgeryId);
        };
    }

    //This just gets the various strings that may be used to describe the surgery action.
    //Its a mess.
    public void SetAction(SurgeryActionPrototype surgeryActionPrototype)
    {
        var targets = surgeryActionPrototype.getTargets();
        if (targets.Length == 0)
            if(surgeryActionPrototype.Treatment != null)
                SurgeryActionName.Text = Loc.GetString(surgeryActionPrototype.Description);
            else
                SurgeryActionName.Text = surgeryActionPrototype.ID;
        else if (surgeryActionPrototype.Remove != null)
        {
            SurgeryActionName.Text = Loc.GetString(surgeryActionPrototype.Description,("bodyPart",surgeryActionPrototype.Remove));
        }
        else if (surgeryActionPrototype.Insert != null)
        {
            SurgeryActionName.Text = Loc.GetString(surgeryActionPrototype.Description,("bodyPart",surgeryActionPrototype.Insert));
        }
        else
            SurgeryActionName.Text = Loc.GetString(surgeryActionPrototype.Description,("bodyPart",targets[0]));

        _surgeryId = surgeryActionPrototype.ID;
    }

    public void SetDisplayControl(Control displayControl)
    {
        SurgeryDisplayContainer.Children.Clear();
        SurgeryDisplayContainer.AddChild(displayControl);
    }
}
